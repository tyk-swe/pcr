#[test]
fn quic_rfc_initial_vectors_decrypt_independently_for_both_versions() {
    // RFC 9001 and RFC 9369 Appendix A, published May 2021 and May 2023.
    for (version, client, server) in [
        (Version::V1, CLIENT_9001, SERVER_9001),
        (Version::V2, CLIENT_9369, SERVER_9369),
    ] {
        for (from_client, wire) in [(true, client), (false, server)] {
            let bytes = unhex(wire).unwrap();
            let packet = parse_packet(&bytes, None).unwrap();
            let opened = Keys::initial(version, &ORIGINAL, from_client)
                .unwrap()
                .open(&packet, None)
                .unwrap();
            assert_eq!(opened.number, if from_client { 2 } else { 1 });
            let frames = parse_frames(&opened.plaintext, 4096).unwrap();
            assert!(
                frames
                    .iter()
                    .any(|f| matches!(f,Frame::Crypto { offset:0,data } if !data.is_empty()))
            );
            let mut tampered = bytes;
            let end = tampered.len() - 1;
            tampered[end] ^= 1;
            assert!(
                Keys::initial(version, &ORIGINAL, from_client)
                    .unwrap()
                    .open(&parse_packet(&tampered, None).unwrap(), None)
                    .is_err()
            );
        }
    }
}
