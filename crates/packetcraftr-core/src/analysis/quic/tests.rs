#[test]
fn quic_file_and_incremental_inputs_preserve_results_and_provenance() {
    use crate::{analysis, capture_file, protocol::builtin};
    use std::io::Cursor;
    let capture = include_bytes!("../../../../../examples/captures/quic-demo-v2.pcapng");
    let log = include_bytes!("../../../../../examples/captures/quic-demo.keys");
    let options = analysis::Options {
        track_sources: true,
        ..analysis::Options::default()
    };
    let mut file = Collector::new(Limits::default()).unwrap();
    file.append_keylog(log, true);
    let mut reader = capture_file::Reader::with_limits(
        Cursor::new(capture),
        capture_file::ReaderLimits::default(),
    )
    .unwrap();
    let mut events = Vec::new();
    let run = analysis::run(&mut reader, builtin::registry(), &options, |record| {
        events.extend(file.observe(&record).unwrap());
        Ok(())
    })
    .unwrap();
    let mut incremental = Collector::new(Limits::default()).unwrap();
    incremental.append_keylog(log, true);
    let mut reader = capture_file::Reader::with_limits(
        Cursor::new(capture),
        capture_file::ReaderLimits::default(),
    )
    .unwrap();
    let mut pipeline = analysis::FramePipeline::new(builtin::registry(), options).unwrap();
    let mut live_events = Vec::new();
    let mut number = 0;
    while let Some(frame) = reader.next_frame().unwrap() {
        number += 1;
        pipeline
            .push(
                number,
                frame,
                |_| Ok(()),
                |record| {
                    live_events.extend(incremental.observe(&record).unwrap());
                    Ok(())
                },
            )
            .unwrap();
    }
    let live_run = pipeline
        .finish(reader.interfaces().to_vec(), |_| Ok(()))
        .unwrap();
    assert_eq!(
        (run.frames_read, run.frames_matched, run.bytes_read),
        (
            live_run.frames_read,
            live_run.frames_matched,
            live_run.bytes_read
        )
    );
    assert_eq!(run.scopes, live_run.scopes);
    let deadline = Deadline::new(Duration::from_secs(30));
    let a = file
        .finish(&deadline, |event| {
            events.push(event);
            Ok(())
        })
        .unwrap();
    let b = incremental
        .finish(&deadline, |event| {
            live_events.push(event);
            Ok(())
        })
        .unwrap();
    assert_eq!(a, b);
    assert_eq!(events, live_events);
    let Event::Connection { connection } = &events[0];
    assert_eq!(connection.source_frames, (1..=number).collect::<Vec<_>>());
    assert_eq!(connection.paths.len(), 2);
    assert_eq!(connection.metrics.key_updates, 1);
    assert_eq!(connection.metrics.validated_paths, 1);
    assert_eq!(connection.negotiated_alpn.as_deref(), Some("quic-test"));
    assert!(
        connection.client_finished_frame.is_some() && connection.server_finished_frame.is_some()
    );
    assert_eq!(
        &connection
            .streams
            .iter()
            .find(|s| s.id == 0 && s.direction == super::Direction::Client)
            .unwrap()
            .ranges[0]
            .data[..],
        b"hello world"
    );
}

