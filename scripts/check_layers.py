SEGMENT = r"[A-Za-z_][A-Za-z0-9_]*"
PATH_START = re.compile(rf"\b(crate|super|self)((?:::{SEGMENT})*)(::\{{)?")
CFG_TEST = re.compile(r"#\[cfg\(test\)\]")
CHAR_LITERAL = re.compile(r"'(?:\\.|[^\\'])'")


def strip_comments_and_strings(text: str) -> str:
    out = []
    i = 0
    while i < len(text):
        pair = text[i:i + 2]
        if pair == "//":
            end = text.find("\n", i)
            i = len(text) if end == -1 else end
        elif pair == "/*":
            depth = 1
            i += 2
            while i < len(text) and depth:
                if text[i:i + 2] == "/*":
                    depth += 1
                    i += 2
                elif text[i:i + 2] == "*/":
                    depth -= 1
                    i += 2
                else:
                    i += 1
            out.append(" ")
        elif text[i] == "r" and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] == "_")) \
                and re.match(r"r(#+)?\"", text[i:]):
            opening = re.match(r"r(#+)?\"", text[i:])
            hashes = opening.group(1) or ""
            closing = '"' + hashes
            end = text.find(closing, i + opening.end())
            i = len(text) if end == -1 else end + len(closing)
            out.append('""')
        elif text[i] == '"':
            i += 1
            while i < len(text) and text[i] != '"':
                i += 2 if text[i] == "\\" else 1
            i += 1
            out.append('""')
        elif text[i] == "'":
            literal = CHAR_LITERAL.match(text, i)
            if literal:
                out.append("'x'")
                i = literal.end()
            else:
                out.append(text[i])
                i += 1
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def balanced_end(text: str, opening: int) -> int:
    depth = 0
    for i in range(opening, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    return len(text)


def strip_test_items(text: str) -> str:
    while True:
        match = CFG_TEST.search(text)
        if match is None:
            return text
        rest = text[match.end():]
        brace = rest.find("{")
        semi = rest.find(";")
        if semi != -1 and (brace == -1 or semi < brace):
            end = match.end() + semi + 1
        elif brace != -1:
            end = balanced_end(text, match.end() + brace)
        else:
            end = len(text)
        text = text[:match.start()] + " " + text[end:]


def split_top_level(group: str) -> list[str]:
    parts = []
    depth = 0
    start = 0
    for i, char in enumerate(group):
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(group[start:i])
            start = i + 1
    parts.append(group[start:])
    return [part.strip() for part in parts if part.strip()]


def resolve_relative(
    prefix: tuple[str, ...], segments: tuple[str, ...]
) -> tuple[str, ...]:
    supers = 0
    while supers < len(segments) and segments[supers] == "super":
        supers += 1
    if supers:
        return prefix[: max(0, len(prefix) - supers)] + segments[supers:]
    if segments and segments[0] == "crate":
        return segments[1:]
    if segments and segments[0] == "self":
        return prefix + segments[1:]
    return prefix + segments


def expand_group(prefix: tuple[str, ...], group: str) -> list[tuple[str, ...]]:
    paths = []
    for entry in split_top_level(group):
        entry = re.sub(rf"\s+as\s+{SEGMENT}$", "", entry)
        brace = entry.find("::{")
        if brace != -1 and entry.endswith("}"):
            head = tuple(entry[:brace].split("::"))
            resolved = resolve_relative(prefix, head)
            paths.extend(expand_group(resolved, entry[brace + 3:-1]))
        elif entry in ("self", "*"):
            if prefix:
                paths.append(prefix)
        else:
            segments = tuple(part for part in entry.split("::") if part != "*")
            resolved = resolve_relative(prefix, segments)
            if resolved:
                paths.append(resolved)
    return paths


def match_prefix(owner: tuple[str, ...], match) -> tuple[str, ...]:
    parts = (match.group(1),) + tuple(
        part for part in match.group(2).split("::") if part
    )
    if parts[0] == "self":
        return resolve_relative(owner, parts)
    return resolve_relative((), parts) if parts[0] == "crate" else resolve_relative(owner, parts)


def crate_paths(text: str, owner: tuple[str, ...] = ()) -> list[tuple[str, ...]]:
    text = strip_test_items(strip_comments_and_strings(text))
    paths = []
    spans = []
    for match in PATH_START.finditer(text):
        if not match.group(3):
            continue
        opening = match.end() - 1
        end = balanced_end(text, opening)
        paths.extend(expand_group(match_prefix(owner, match), text[opening + 1:end - 1]))
        spans.append((match.start(), end))
    for start, end in reversed(spans):
        text = text[:start] + " " * (end - start) + text[end:]
    for match in PATH_START.finditer(text):
        if match.group(3):
            continue
        resolved = match_prefix(owner, match)
        if resolved:
            paths.append(resolved)
    return paths


def layer_of(table: dict[tuple[str, ...], int], path: tuple[str, ...]) -> int | None:
    for length in range(len(path), 0, -1):
        if path[:length] in table:
            return table[path[:length]]
    return None


def owner_path(src: Path, path: Path) -> tuple[str, ...] | None:
    rel = path.relative_to(src)
    if len(rel.parts) == 1 and rel.name in ("lib.rs", "main.rs"):
        return None
    parts = list(rel.parts)
    parts[-1] = parts[-1][:-3]
    return tuple(parts)


def is_test_path(src: Path, path: Path) -> bool:
    rel = path.relative_to(src)
    return rel.name == "tests.rs" or "tests" in rel.parts[:-1]


def allowlisted(
    allowlist, crate: str, owner: tuple[str, ...], target: tuple[str, ...]
) -> int | None:
    for index, (allowed_crate, owner_prefix, target_prefix, _reason) in enumerate(allowlist):
        if (
            allowed_crate == crate
            and owner[: len(owner_prefix)] == owner_prefix
            and target[: len(target_prefix)] == target_prefix
        ):
            return index
    return None


def check_crate(crate: str, src: Path, table, allowlist, used: set[int]) -> list[str]:
    problems = []
    for path in sorted(src.rglob("*.rs")):
        owner = owner_path(src, path)
        if owner is None or is_test_path(src, path):
            continue
        owner_layer = layer_of(table, owner)
        shown = "::".join(owner)
        if owner_layer is None:
            problems.append(f"{crate}: {path} module {shown} is not in the layer table")
            continue
        for target in crate_paths(path.read_text(errors="replace"), owner):
            target_layer = layer_of(table, target)
            if target_layer is None or target_layer <= owner_layer:
                continue
            index = allowlisted(allowlist, crate, owner, target)
            if index is not None:
                used.add(index)
                continue
            problems.append(
                f"{crate}: {path} {shown} (layer {owner_layer}) depends on "
                f"{'::'.join(target)} (layer {target_layer})"
            )
    return problems


def check_workspace(root: Path, layers=LAYERS, allowlist=ALLOWLIST) -> list[str]:
    problems = []
    used: set[int] = set()
    for crate, table in layers.items():
        src = root / "crates" / crate / "src"
        if not src.is_dir():
            problems.append(f"{crate}: missing source directory {src}")
            continue
        problems.extend(check_crate(crate, src, table, allowlist, used))
    for index, (crate, owner_prefix, target_prefix, _reason) in enumerate(allowlist):
        if index not in used and crate in layers:
            problems.append(
                f"{crate}: stale allowlist entry {'::'.join(owner_prefix)} -> "
                f"{'::'.join(target_prefix)}"
            )
    return problems


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parents[1]
    )
    args = parser.parse_args(argv)
    problems = check_workspace(args.root.resolve())
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print(f"{len(problems)} layer problem(s)", file=sys.stderr)
        return 1
    print("all crate modules depend only on their own layer or a lower one")
    return 0


if __name__ == "__main__":
    sys.exit(main())
